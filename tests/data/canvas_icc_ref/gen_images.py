"""Writes the test images and ICC profiles of the canvas colour probe, standard library only.

    python -I gen_images.py <out dir>

<out dir>/images/*.png|jpg, <out dir>/profiles/*.icc (built by hand: matrix/TRC, ICC v2.1),
<out dir>/images.json (id, file, what the tag says). Nothing is downloaded. The pixels are the
same 16x16 gradient in every image (R from x, G from y, B from x+y), so the files differ only
in the colour tag they carry.
"""
import json
import math
import os
import struct
import sys
import zlib

D50 = (0.9642, 1.0, 0.8249)
D65_XY = (0.3127, 0.3290)
D50_XY = (0.3457, 0.3585)
# name: (primaries xy R,G,B, white xy, trc)
SPACES = {
    "displayp3": (((0.680, 0.320), (0.265, 0.690), (0.150, 0.060)), D65_XY, ("para-srgb",)),
    "adobergb": (((0.640, 0.330), (0.210, 0.710), (0.150, 0.060)), D65_XY, ("gamma", 563 / 256)),
    "rec2020": (((0.708, 0.292), (0.170, 0.797), (0.131, 0.046)), D65_XY, ("gamma", 2.4)),
    "prophoto": (((0.7347, 0.2653), (0.1596, 0.8404), (0.0366, 0.0001)), D50_XY, ("gamma", 1.8)),
    "srgb": (((0.640, 0.330), (0.300, 0.600), (0.150, 0.060)), D65_XY, ("para-srgb",)),
}


def mat_mul(a, b):
    return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]


def mat_vec(m, v):
    return [sum(m[i][k] * v[k] for k in range(3)) for i in range(3)]


def mat_inv(m):
    a, b, c = m[0]
    d, e, f = m[1]
    g, h, i = m[2]
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    return [[(e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det],
            [(f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det],
            [(d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det]]


def xy_to_xyz(xy):
    x, y = xy
    return [x / y, 1.0, (1 - x - y) / y]


BRADFORD = [[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]]


def adapt(src_white, dst_white):
    s = mat_vec(BRADFORD, src_white)
    d = mat_vec(BRADFORD, dst_white)
    scale = [[d[0] / s[0], 0, 0], [0, d[1] / s[1], 0], [0, 0, d[2] / s[2]]]
    return mat_mul(mat_inv(BRADFORD), mat_mul(scale, BRADFORD))


def colorants_d50(prim, white_xy):
    """The rXYZ, gXYZ, bXYZ columns adapted (Bradford) to the D50 PCS."""
    cols = [xy_to_xyz(p) for p in prim]
    m = [[cols[j][i] for j in range(3)] for i in range(3)]
    s = mat_vec(mat_inv(m), xy_to_xyz(white_xy))
    rgb2xyz = [[m[i][j] * s[j] for j in range(3)] for i in range(3)]
    ad = adapt(xy_to_xyz(white_xy), list(D50))
    out = mat_mul(ad, rgb2xyz)
    return [[out[i][j] for i in range(3)] for j in range(3)]  # per channel XYZ


def s15(v):
    return struct.pack(">i", int(round(v * 65536)))


def tag_xyz(v):
    return b"XYZ \0\0\0\0" + s15(v[0]) + s15(v[1]) + s15(v[2])


def tag_text(s):
    return b"text\0\0\0\0" + s.encode("ascii") + b"\0"


def tag_desc(s):
    b = s.encode("ascii") + b"\0"
    return (b"desc\0\0\0\0" + struct.pack(">I", len(b)) + b + struct.pack(">II", 0, 0)
            + struct.pack(">HB", 0, 0) + b"\0" * 67)


def tag_trc(trc):
    if trc[0] == "gamma":
        return b"curv\0\0\0\0" + struct.pack(">IH", 1, int(round(trc[1] * 256))) + b"\0\0"
    # parametric type 3: Y = (aX+b)^g for X >= d, cX otherwise (the sRGB curve)
    return (b"para\0\0\0\0" + struct.pack(">HH", 3, 0) + s15(2.4) + s15(1 / 1.055) + s15(0.055 / 1.055)
            + s15(1 / 12.92) + s15(0.04045))


def pad4(b):
    return b + b"\0" * (-len(b) % 4)


def build_icc(name):
    prim, white, trc = SPACES[name]
    cols = colorants_d50(prim, white)
    trc_b = pad4(tag_trc(trc))
    tags = [(b"desc", pad4(tag_desc("invisible probe " + name))),
            (b"cprt", pad4(tag_text("public domain, generated by gen_images.py"))),
            (b"wtpt", tag_xyz(D50)),
            (b"rXYZ", tag_xyz(cols[0])), (b"gXYZ", tag_xyz(cols[1])), (b"bXYZ", tag_xyz(cols[2])),
            (b"rTRC", trc_b), (b"gTRC", trc_b), (b"bTRC", trc_b)]
    off = 128 + 4 + 12 * len(tags)
    table = struct.pack(">I", len(tags))
    body = b""
    seen = {}
    for sig, data in tags:
        if data in seen and sig.endswith(b"TRC"):
            o = seen[data]
        else:
            o = off + len(body)
            body += data
            seen[data] = o
        table += sig + struct.pack(">II", o, len(data))
    size = 128 + len(table) + len(body)
    hdr = (struct.pack(">I", size) + b"\0\0\0\0" + bytes([2, 0x10, 0, 0]) + b"mntrRGB XYZ "
           + struct.pack(">6H", 2026, 11, 9, 0, 0, 0) + b"acsp"
           + b"\0" * 28  # platform, flags, manufacturer, model, attributes (8), rendering intent
           + s15(D50[0]) + s15(D50[1]) + s15(D50[2]) + b"\0" * 4 + b"\0" * 16 + b"\0" * 28)
    assert len(hdr) == 128, len(hdr)
    return hdr + table + body


def pixels():
    rows = []
    for y in range(16):
        rows.append([(x * 17, y * 17, (x + y) * 17 // 2) for x in range(16)])
    return rows


def chunk(typ, data):
    c = typ + data
    return struct.pack(">I", len(data)) + c + struct.pack(">I", zlib.crc32(c) & 0xFFFFFFFF)


def png(extra):
    raw = b"".join(b"\0" + bytes(v for px in row for v in px) for row in pixels())
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 16, 16, 8, 2, 0, 0, 0))
            + b"".join(chunk(t, d) for t, d in extra) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def iccp(name, profile):
    return (b"iCCP", name.encode() + b"\0\0" + zlib.compress(profile, 9))


def chrm(prim, white):
    vals = [white[0], white[1]] + [c for p in prim for c in p]
    return (b"cHRM", b"".join(struct.pack(">I", int(round(v * 100000))) for v in vals))


# ---- baseline JPEG, 4:4:4, quantisation all 1, own Huffman tables (no tables copied from anywhere)
ZIGZAG = [0, 1, 8, 16, 9, 2, 3, 10, 17, 24, 32, 25, 18, 11, 4, 5, 12, 19, 26, 33, 40, 48, 41, 34, 27, 20, 13, 6, 7, 14,
          21, 28, 35, 42, 49, 56, 57, 50, 43, 36, 29, 22, 15, 23, 30, 37, 44, 51, 58, 59, 52, 45, 38, 31, 39, 46, 53,
          60, 61, 54, 47, 55, 62, 63]
AC_SYMS = [0x00, 0xF0] + [(r << 4) | s for r in range(16) for s in range(1, 11)]  # 162 symbols, 8-bit codes 0..161


def dct8(block):
    out = [0.0] * 64
    for u in range(8):
        for v in range(8):
            s = 0.0
            for x in range(8):
                for y in range(8):
                    s += block[y * 8 + x] * math.cos((2 * x + 1) * u * math.pi / 16) * math.cos((2 * y + 1) * v * math.pi / 16)
            cu = 1 / math.sqrt(2) if u == 0 else 1
            cv = 1 / math.sqrt(2) if v == 0 else 1
            out[v * 8 + u] = 0.25 * cu * cv * s
    return out


def jpeg(profile):
    ycc = []
    for row in pixels():
        r = []
        for (R, G, B) in row:
            r.append((0.299 * R + 0.587 * G + 0.114 * B,
                      -0.168736 * R - 0.331264 * G + 0.5 * B + 128,
                      0.5 * R - 0.418688 * G - 0.081312 * B + 128))
        ycc.append(r)
    bits = []

    def put(code, n):
        for i in range(n - 1, -1, -1):
            bits.append((code >> i) & 1)

    def cat(v):
        return 0 if v == 0 else abs(v).bit_length()

    def amp(v, s):
        return v if v >= 0 else v + (1 << s) - 1

    pred = [0, 0, 0]
    for by in range(2):
        for bx in range(2):
            for c in range(3):
                blk = [ycc[by * 8 + y][bx * 8 + x][c] - 128 for y in range(8) for x in range(8)]
                co = [int(round(v)) for v in dct8(blk)]
                zz = [co[i] for i in ZIGZAG]
                d = zz[0] - pred[c]
                pred[c] = zz[0]
                s = cat(d)
                put(s, 4)  # DC symbol s has the 4-bit code s
                if s:
                    put(amp(d, s), s)
                run = 0
                last = max([i for i in range(1, 64) if zz[i]] or [0])
                for i in range(1, last + 1):
                    v = zz[i]
                    if v == 0:
                        run += 1
                        continue
                    while run > 15:
                        put(AC_SYMS.index(0xF0), 8)
                        run -= 16
                    s = cat(v)
                    put(AC_SYMS.index((run << 4) | s), 8)
                    put(amp(v, s), s)
                    run = 0
                if last < 63:
                    put(AC_SYMS.index(0x00), 8)
    while len(bits) % 8:
        bits.append(1)
    data = bytearray()
    for i in range(0, len(bits), 8):
        b = int("".join(map(str, bits[i:i + 8])), 2)
        data.append(b)
        if b == 0xFF:
            data.append(0)

    def seg(m, payload):
        return bytes([0xFF, m]) + struct.pack(">H", len(payload) + 2) + payload

    icc = b"ICC_PROFILE\0" + bytes([1, 1]) + profile
    out = b"\xFF\xD8" + seg(0xE0, b"JFIF\0\x01\x01\0\0\x01\0\x01\0\0") + seg(0xE2, icc)
    out += seg(0xDB, bytes([0]) + bytes([1] * 64))
    out += seg(0xC0, bytes([8]) + struct.pack(">HH", 16, 16) + bytes([3, 1, 0x11, 0, 2, 0x11, 0, 3, 0x11, 0]))
    out += seg(0xC4, bytes([0x00]) + bytes([0, 0, 0, 12] + [0] * 12) + bytes(range(12)))
    out += seg(0xC4, bytes([0x10]) + bytes([0] * 7 + [len(AC_SYMS)] + [0] * 8) + bytes(AC_SYMS))
    out += seg(0xDA, bytes([3, 1, 0x00, 2, 0x00, 3, 0x00, 0, 63, 0])) + bytes(data) + b"\xFF\xD9"
    return out


def build_images():
    """The ten test images, in memory: a list of (id, extension, bytes, what the tag says),
    and the five generated ICC profiles by name. Deterministic: the same bytes on every run."""
    profs = {n: build_icc(n) for n in SPACES}
    p3prim, p3white, _ = SPACES["displayp3"]
    imgs = [
        ("iccp-displayp3", "png", png([iccp("p3", profs["displayp3"])]), "iCCP Display P3 (matrix, sRGB-curve parametric TRC)"),
        ("iccp-adobergb", "png", png([iccp("a98", profs["adobergb"])]), "iCCP Adobe RGB (1998) (matrix, gamma 563/256)"),
        ("iccp-rec2020", "png", png([iccp("r2020", profs["rec2020"])]), "iCCP Rec.2020 primaries (matrix, gamma 2.4)"),
        ("iccp-prophoto", "png", png([iccp("pp", profs["prophoto"])]), "iCCP ProPhoto RGB (matrix, gamma 1.8, D50 white)"),
        ("iccp-srgb", "png", png([iccp("s", profs["srgb"])]), "iCCP sRGB primaries (matrix, sRGB parametric TRC): control"),
        ("cicp-p3", "png", png([(b"cICP", bytes([12, 13, 0, 1]))]), "cICP primaries 12 (Display P3), transfer 13 (sRGB), full range"),
        ("gama-chrm-p3", "png", png([(b"gAMA", struct.pack(">I", 45455)), chrm(p3prim, p3white)]), "gAMA 45455 + cHRM of Display P3"),
        ("srgb-chunk", "png", png([(b"sRGB", b"\0")]), "sRGB chunk, perceptual"),
        ("untagged", "png", png([]), "no colour tag"),
        ("jpeg-icc-displayp3", "jpg", jpeg(profs["displayp3"]), "JPEG (own encoder) with APP2 ICC Display P3"),
    ]
    return imgs, profs


def images_json(imgs):
    """What the page fetches as images.json: id, URL (relative) and the tag, per image."""
    return [{"id": iid, "file": "images/%s.%s" % (iid, ext), "tag": what}
            for iid, ext, _data, what in imgs]


def main():
    out = sys.argv[1]
    os.makedirs(os.path.join(out, "images"), exist_ok=True)
    os.makedirs(os.path.join(out, "profiles"), exist_ok=True)
    imgs, profs = build_images()
    for n, p in profs.items():
        with open(os.path.join(out, "profiles", n + ".icc"), "wb") as f:
            f.write(p)
    for (iid, ext, data, _what), meta in zip(imgs, images_json(imgs)):
        with open(os.path.join(out, meta["file"]), "wb") as f:
            f.write(data)
    with open(os.path.join(out, "images.json"), "w") as f:
        json.dump(images_json(imgs), f, indent=1)
    print("wrote %d images and %d profiles to %s" % (len(imgs), len(profs), out))


if __name__ == "__main__":
    main()
